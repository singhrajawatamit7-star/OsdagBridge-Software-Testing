"""
Design Report Generation module for OsdagBridge.
Produces engineering design calculations, summaries, verification tables,
and printable HTML/Markdown artifacts compliant with standard QA reporting.
"""

from typing import Dict, Any
from datetime import datetime
from .models import BridgeProject, DesignSummary


class ReportGenerator:
    """Generates formatted reports for OsdagBridge projects."""

    @classmethod
    def generate_markdown_report(cls, project: BridgeProject, summary: DesignSummary) -> str:
        date_str = datetime.now().strftime("%Y-%m-%d %H:%M:%S")
        status_banner = "✅ DESIGN SAFE - SATISFIES ALL IRC / IS CRITERIA" if summary.is_safe else "❌ DESIGN UNSAFE - CRITERIA EXCEEDED"

        lines = [
            f"# OSDAGBRIDGE STRUCTURAL DESIGN CALCULATION REPORT",
            f"**Report Generated On:** {date_str}  ",
            f"**Project Status:** {status_banner}  ",
            f"",
            f"---",
            f"## 1. Project Information",
            f"- **Project ID:** `{project.project_id}`",
            f"- **Project Title:** {project.project_name}",
            f"- **Location:** {project.location}",
            f"- **Lead Engineer:** {project.engineer_name}",
            f"- **Bridge Type:** {project.bridge_type.replace('_', ' ')}",
            f"- **Steel Grade:** {project.steel_grade}",
            f"- **Concrete Grade:** {project.concrete_grade}",
            f"- **Design Live Load:** {project.vehicle_loading.replace('_', ' ')}",
            f"",
            f"## 2. Geometry & Section Properties",
            f"| Parameter | Value | Unit |",
            f"| :--- | :--- | :--- |",
            f"| Effective Span Length | {project.geometry.span_length:.2f} | m |",
            f"| Carriageway Width | {project.geometry.carriageway_width:.2f} | m |",
            f"| Number of Main Girders | {project.geometry.number_of_main_girders} | nos |",
            f"| Main Girder Spacing | {project.geometry.girder_spacing:.2f} | m |",
            f"| Deck Slab Thickness | {project.geometry.deck_slab_thickness:.1f} | mm |",
            f"| Web Depth | {project.girder_dimensions.web_depth:.1f} | mm |",
            f"| Web Thickness | {project.girder_dimensions.web_thickness:.1f} | mm |",
            f"| Flange Width | {project.girder_dimensions.flange_width:.1f} | mm |",
            f"| Flange Thickness | {project.girder_dimensions.flange_thickness:.1f} | mm |",
            f"",
            f"## 3. Analysis Demand & Capacity Summary",
            f"| Structural Parameter | Demand / Value | Capacity / Limit | Utilization | Unit |",
            f"| :--- | :--- | :--- | :--- | :--- |",
            f"| Bending Moment (ULS) | {summary.design_moment:,.2f} | {summary.moment_capacity:,.2f} | {summary.design_moment/summary.moment_capacity:.2f} | kNm |",
            f"| Shear Force (ULS) | {summary.design_shear_force:,.2f} | {summary.shear_capacity:,.2f} | {summary.design_shear_force/summary.shear_capacity:.2f} | kN |",
            f"| Live Load Deflection (SLS)| {summary.max_deflection:.2f} | {summary.allowable_deflection:.2f} | {summary.max_deflection/summary.allowable_deflection:.2f} | mm |",
            f"",
            f"## 4. Code Compliance Verification Table",
            f"| Check Description | Actual Value | Limit | Ratio | Status | Code Clause |",
            f"| :--- | :--- | :--- | :--- | :--- | :--- |",
        ]

        for c in summary.checks:
            st = "PASS" if c.status == "PASS" else "**FAIL**"
            lines.append(f"| {c.check_name} | {c.actual_value} {c.unit} | {c.allowable_limit} {c.unit} | {c.ratio:.3f} | {st} | {c.clause_reference} |")

        if summary.failure_reasons:
            lines.append("")
            lines.append("## 5. Engineering Warnings & Deficiencies")
            for reason in summary.failure_reasons:
                lines.append(f"- ⚠️ {reason}")

        lines.append("")
        lines.append("---")
        lines.append("*Generated by OsdagBridge Automated QA Engine & Verification Suite*")
        return "\n".join(lines)

    @classmethod
    def generate_html_report(cls, project: BridgeProject, summary: DesignSummary) -> str:
        date_str = datetime.now().strftime("%Y-%m-%d %H:%M:%S")
        status_color = "#28a745" if summary.is_safe else "#dc3545"
        status_text = "SAFE / ACCEPTABLE" if summary.is_safe else "UNSAFE / LIMITS EXCEEDED"

        rows = ""
        for c in summary.checks:
            badge_color = "#28a745" if c.status == "PASS" else "#dc3545"
            rows += f"""
            <tr>
                <td><strong>{c.check_name}</strong></td>
                <td>{c.actual_value} {c.unit}</td>
                <td>{c.allowable_limit} {c.unit}</td>
                <td>{c.ratio:.3f}</td>
                <td><span style="background:{badge_color};color:white;padding:3px 8px;border-radius:4px;">{c.status}</span></td>
                <td><code>{c.clause_reference}</code></td>
            </tr>
            """

        html = f"""<!DOCTYPE html>
<html>
<head>
    <meta charset="utf-8">
    <title>OsdagBridge Design Report - {project.project_id}</title>
    <style>
        body {{ font-family: -apple-system, BlinkMacSystemFont, "Segoe UI", Roboto, Helvetica, Arial, sans-serif; margin: 30px; color: #212529; }}
        h1, h2 {{ color: #0d3c61; }}
        .header-box {{ border-left: 6px solid {status_color}; background: #f8f9fa; padding: 16px; margin-bottom: 24px; }}
        table {{ width: 100%; border-collapse: collapse; margin-top: 15px; margin-bottom: 25px; }}
        th, td {{ border: 1px solid #dee2e6; padding: 10px; text-align: left; font-size: 14px; }}
        th {{ background: #e9ecef; }}
        .badge {{ display: inline-block; padding: 4px 10px; border-radius: 4px; font-weight: bold; color: white; background: {status_color}; }}
        .footer {{ font-size: 12px; color: #6c757d; margin-top: 40px; border-top: 1px solid #dee2e6; padding-top: 10px; }}
    </style>
</head>
<body>
    <div class="header-box">
        <h1>OsdagBridge - Plate Girder Design Report</h1>
        <p><strong>Project:</strong> {project.project_name} (ID: {project.project_id}) | <strong>Date:</strong> {date_str}</p>
        <p><strong>Overall Status:</strong> <span class="badge">{status_text}</span></p>
    </div>

    <h2>1. General Specification</h2>
    <table>
        <tr><th>Location</th><td>{project.location}</td><th>Engineer</th><td>{project.engineer_name}</td></tr>
        <tr><th>Bridge Type</th><td>{project.bridge_type}</td><th>Loading Standard</th><td>{project.vehicle_loading}</td></tr>
        <tr><th>Steel Grade</th><td>{project.steel_grade}</td><th>Concrete Grade</th><td>{project.concrete_grade}</td></tr>
        <tr><th>Effective Span</th><td>{project.geometry.span_length} m</td><th>Carriageway</th><td>{project.geometry.carriageway_width} m</td></tr>
    </table>

    <h2>2. Structural Design Verification (IS 800:2007 & IRC:24)</h2>
    <table>
        <thead>
            <tr>
                <th>Check Description</th>
                <th>Actual Demand</th>
                <th>Permissible Capacity</th>
                <th>Utilization Ratio</th>
                <th>Status</th>
                <th>Standard Clause</th>
            </tr>
        </thead>
        <tbody>
            {rows}
        </tbody>
    </table>

    <div class="footer">
        OsdagBridge Open-Source QA & Verification Suite &bull; IIT Bombay / Osdag Design Specifications
    </div>
</body>
</html>"""
        return html
